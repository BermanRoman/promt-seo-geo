// Общие правки текста для OG-картинок и выгрузок для нейросетей.

// Короткие предлоги и союзы (одна-две буквы) не висят в конце строки: после них неразрывный пробел.
export const glue = (t) => t.replace(/(?<=^|[\s(«])([а-яёА-ЯЁ]{1,2})\s(?=\S)/g, '$1 ');
// без разметки Markdown — для description, llms.txt и подсчёта слов
export const plain = (md) => md.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
  .replace(/[*_`>#]/g, '').replace(/\s+/g, ' ').trim();
